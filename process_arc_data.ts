import fs from 'fs';
import path from 'path';

interface ArcTask {
  train: { input: number[][], output: number[][] }[];
  test: { input: number[][] }[];
}

interface ArcSolutions {
  [taskId: string]: number[][][];
}

function calculateDifficulty(task: ArcTask): 'low' | 'medium' | 'high' {
  let maxGridSize = 0;
  let uniqueColors = new Set<number>();

  task.train.forEach(ex => {
    maxGridSize = Math.max(maxGridSize, ex.input.length * ex.input[0].length);
    maxGridSize = Math.max(maxGridSize, ex.output.length * ex.output[0].length);
    
    ex.input.forEach(row => row.forEach(c => uniqueColors.add(c)));
    ex.output.forEach(row => row.forEach(c => uniqueColors.add(c)));
  });

  const score = maxGridSize + (uniqueColors.size * 10);

  if (score < 150) return 'low';
  if (score < 400) return 'medium';
  return 'high';
}

function shuffleArray<T>(array: T[]): T[] {
  const newArray = [...array];
  for (let i = newArray.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [newArray[i], newArray[j]] = [newArray[j], newArray[i]];
  }
  return newArray;
}

function main() {
  const challengesPath = path.join(process.cwd(), 'public', 'challenges.json');
  const solutionsPath = path.join(process.cwd(), 'public', 'solutions.json');

  if (!fs.existsSync(challengesPath) || !fs.existsSync(solutionsPath)) {
    console.error('Error: Please upload challenges.json and solutions.json to the public directory.');
    process.exit(1);
  }

  const challenges: Record<string, ArcTask> = JSON.parse(fs.readFileSync(challengesPath, 'utf-8'));
  const solutions: ArcSolutions = JSON.parse(fs.readFileSync(solutionsPath, 'utf-8'));

  const lowTasks: any[] = [];
  const mediumTasks: any[] = [];
  const highTasks: any[] = [];

  const scores: number[] = [];
  for (const [taskId, task] of Object.entries(challenges)) {
    if (!solutions[taskId]) continue;

    let maxGridSize = 0;
    let uniqueColors = new Set<number>();

    task.train.forEach(ex => {
      maxGridSize = Math.max(maxGridSize, ex.input.length * ex.input[0].length);
      maxGridSize = Math.max(maxGridSize, ex.output.length * ex.output[0].length);
      
      ex.input.forEach(row => row.forEach(c => uniqueColors.add(c)));
      ex.output.forEach(row => row.forEach(c => uniqueColors.add(c)));
    });

    const score = maxGridSize + (uniqueColors.size * 10);
    scores.push(score);
  }
  scores.sort((a, b) => a - b);
  console.log('Scores:', scores.join(', '));
  process.exit(0);

  // Shuffle tasks
  const shuffledLow = shuffleArray(lowTasks);
  const shuffledMedium = shuffleArray(mediumTasks);
  const shuffledHigh = shuffleArray(highTasks);

  // Select for Stage 1 (4 low, 4 medium, 4 high)
  const stage1 = [
    ...shuffledLow.slice(0, 4),
    ...shuffledMedium.slice(0, 4),
    ...shuffledHigh.slice(0, 4)
  ];

  // Select for Stage 2 (next 4 low, 4 medium, 4 high)
  const stage2 = [
    ...shuffledLow.slice(4, 8),
    ...shuffledMedium.slice(4, 8),
    ...shuffledHigh.slice(4, 8)
  ];

  const outputContent = `// Auto-generated by process_arc_data.ts
export interface TaskData {
  id: string;
  difficulty: 'low' | 'medium' | 'high';
  train: { input: number[][], output: number[][] }[];
  test_input: number[][];
  ground_truth: number[][];
  explanation_en: string;
  explanation_zh: string;
  trap_answer?: number[][];
}

export const STAGE_1_TASKS: TaskData[] = ${JSON.stringify(stage1, null, 2)};

export const STAGE_2_TASKS: TaskData[] = ${JSON.stringify(stage2, null, 2)};
`;

  fs.writeFileSync(path.join(process.cwd(), 'src/lib/arc_data.ts'), outputContent);
  console.log('Successfully generated src/lib/arc_data.ts with randomly selected tasks!');
}

main();
